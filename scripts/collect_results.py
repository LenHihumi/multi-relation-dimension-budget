"""Collect every number the system paper needs into one markdown file (single source of truth).

Reading the JSONs by hand is how a paper ends up with two versions of the same ratio.  This prints the
tables in the order they appear in the draft, so the LaTeX can be checked line by line against it.
"""
import glob
import json
import os

from sb_paths import SB_ROOT, SB_OUT, SB_CACHE, SB_MODELS, REPO  # paths resolve relative to the deposit
O = SB_OUT
L = []
add = L.append

add('# Measured numbers (generated by collect_results.py)\n')

add('## Five encoders, In-shop (52,591 rows)\n')
add('| encoder | r_cat | r_item | umax MB | shared MB | bytes ratio | item mAP | cat mAP | d item | d cat | QPS umax | QPS shared |')
add('|---|---|---|---|---|---|---|---|---|---|---|---|')
rows = []
for f in sorted(glob.glob(os.path.join(O, 'shared_index__*__inshop.json'))):
    d = json.load(open(f))
    m, u, s = d['meta'], d['umax'], d['share-i8']
    rows.append((m['enc'], m['r_cat'], m['r_item'], u['bytes']['total'] / 1e6,
                 s['bytes']['total'] / 1e6, s['bytes']['total'] / u['bytes']['total'],
                 u['mAP_inst'], s['mAP_inst'], u['mAP_cat'], s['mAP_cat'],
                 100 * (s['mAP_inst'] / u['mAP_inst'] - 1), 100 * (s['mAP_cat'] / u['mAP_cat'] - 1),
                 u.get('qps_e2e', float('nan')), s.get('qps_e2e', float('nan'))))
for r in rows:
    add('| %s | %d | %d | %.1f | %.1f | %.3f | %.4f | %.4f | %+.1f%% | %+.1f%% | %.0f | %.0f |'
        % (r[0], r[1], r[2], r[3], r[4], r[5], r[6], r[7], r[10], r[11], r[12], r[13]))

add('\n## ImageNet 1,281,167 rows, measured budgets (r_inst=160, r_cat=128)\n')
d = json.load(open(os.path.join(O, 'shared_index__clip_vitl14__imagenet1m.json')))
add('| design | mAP inst | mAP cat | MB | vs umax | QPS |')
add('|---|---|---|---|---|---|')
for k in ('umax', 'indep', 'share-f32', 'share-i8'):
    v = d[k]
    add('| %s | %.4f | %.4f | %.1f | %.3f | %.0f |'
        % (k, v['mAP_inst'], v['mAP_cat'], v['bytes']['total'] / 1e6,
           v['bytes']['total'] / d['umax']['bytes']['total'], v.get('qps_e2e', float('nan'))))

add('\n## ImageNet latency and memory (single-thread per query, 300 queries)\n')
p = os.path.join(O, 'ann_latency__imagenet1m.json')
if os.path.exists(p):
    a = json.load(open(p))
    add('| design | build s | p50 ms | p99 ms | QPS | index MB | RSS delta MB | mAP inst | mAP cat |')
    add('|---|---|---|---|---|---|---|---|---|')
    for k in ('umax', 'umin', 'share'):
        v = a[k]
        add('| %s | %.1f | %.2f | %.2f | %.0f | %.0f | %.0f | %.4f | %.4f |'
            % (k, v['build_s'], v['p50_ms'], v['p99_ms'], v['qps'], v['bytes_mb'],
               v['rss_delta_mb'], v['mAP_inst'], v['mAP_cat']))

add('\n## Scaling (Gaussian vectors, d=48, M=32, ef=64; system measurements only)\n')
add('| n | build s | QPS | p99 ms | shared GB | uniform GB | ratio |')
add('|---|---|---|---|---|---|---|')
for f in ('index_scaling_100k.json', 'index_scaling_1m.json', 'index_scaling_10m.json'):
    p = os.path.join(O, f)
    if not os.path.exists(p):
        continue
    s = json.load(open(p))['rows'][0]
    add('| %d | %.1f | %.0f | %.2f | %.2f | %.2f | %.2f |'
        % (s['n'], s['build_s'], s['qps'], s['p99_ms'],
           s['bytes_total_shared'] / 1e9, s['bytes_uniform_f32_160'] / 1e9,
           s['bytes_total_shared'] / s['bytes_uniform_f32_160']))

add('\n## Quantisation drift, CLIP/In-shop, r=160, 500 queries\n')
p = os.path.join(O, 'quant_drift__clip_inshop.json')
if os.path.exists(p):
    q = json.load(open(p))
    add('| variant | bytes/vector | top-10 overlap | p95 rank displacement |')
    add('|---|---|---|---|')
    add('| float32 | 640 | 1.000 | 0 |')
    byts = {'int8': 160, 'fp8e4m3': 160, 'pq32x8': 32, 'pq16x8': 16, 'pq8x8': 8}
    for k, v in q['variants'].items():
        add('| %s | %d | %.3f | %.0f |' % (k, byts.get(k, 0), v['overlap'], v['p95_disp']))

add('\n## Crossover check: predicted vs measured bytes ratio\n')
add('| cell | r_cat | r_item | predicted | measured | diff |')
add('|---|---|---|---|---|---|')
for f in sorted(glob.glob(os.path.join(O, 'shared_index__*__inshop.json'))) + \
        [os.path.join(O, 'shared_index__clip_vitl14__imagenet1m.json')]:
    d = json.load(open(f))
    m = d['meta']
    links = 2 * m['M'] * 4
    pred = (4 * m['r_cat'] + m['r_item'] + links) / (4 * m['r_item'] + links)
    meas = d['share-i8']['bytes']['total'] / d['umax']['bytes']['total']
    add('| %s/%s | %d | %d | %.3f | %.3f | %+.3f |'
        % (m['enc'], m['ds'], m['r_cat'], m['r_item'], pred, meas, meas - pred))

print('\n'.join(L))
open(SB_OUT + '/RESULTS.md', 'w').write('\n'.join(L))
